function collectHeadlines(data) {
    const all = [];
    for (const event of data.events || []) {
        const variants = Array.isArray(event.variants) && event.variants.length ? event.variants : [event];
        for (const variant of variants) {
            for (const headline of variant.headlines || []) {
                const value = String(headline || '').trim();
                if (value) all.push(value);
            }
        }
    }
    return [...new Set(all)];
}

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const headlines = collectHeadlines(source);
if (headlines.length !== TARGETS.length) {
    throw new Error(`Expected ${TARGETS.length} unique headlines, found ${headlines.length}. Review the translation seed after upstream changes.`);
}

const entries = Object.fromEntries(headlines.map((headline, index) => [headline, {
    source: headline,
    target: TARGETS[index],
    status: 'needs-review',
    note: '项目自创新闻文案；已按国服术语初译，建议由中文维护者复核语气与专名。',
}]));

fs.writeFileSync(outputPath, `${JSON.stringify({
    locale: 'zh-CN',
    version: 1,
    readme: '新闻句子为项目自创文案；专有名词按国服术语表处理，可在翻译维护页逐条纠错。',
    entries,
}, null, 2)}\n`, 'utf8');
